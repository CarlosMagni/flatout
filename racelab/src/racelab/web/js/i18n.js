// Translations (English default, French available) and the language choice.
//
// The language is fixed for the lifetime of a page: switching it saves the choice
// and reloads (see setLang), so views never need to re-render their texts.
//
// Keys are flat and namespaced ("race.act.start"). A value is either a string or,
// for plurals, an object {one, other} picked from the count passed as `n`.
// `{name}` placeholders are filled from the `vars` argument of t().

const STORAGE_KEY = "racelab.lang";
const LOCALES = { en: "en-GB", fr: "fr-FR" };

function detect() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in LOCALES) return saved;
  } catch { /* storage unavailable (private mode, blocked) */ }
  try {
    if (String(navigator.language || "").toLowerCase().startsWith("fr")) return "fr";
  } catch { /* no navigator (tests) */ }
  return "en";
}

// options of the language selector (endonyms: never translated)
export const LANGUAGES = [
  { value: "en", label: "EN", title: "English" },
  { value: "fr", label: "FR", title: "Français" },
];

export const lang = detect();
export const locale = LOCALES[lang];
if (typeof document !== "undefined") document.documentElement.lang = lang;

export function setLang(next) {
  if (!(next in LOCALES) || next === lang) return;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* storage unavailable */ }
  location.reload();
}

