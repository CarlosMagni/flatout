export const DICTIONARIES = { en, fr };

// ============================================================ lookup

const dict = DICTIONARIES[lang];
const rules = new Intl.PluralRules(locale);
const warned = new Set();

function lookup(key) {
  return dict[key] ?? en[key];
}

// t("race.on_track", { n: 3 }) ; plural entries use vars.n to pick one/other
export function t(key, vars) {
  let entry = lookup(key);
  if (entry === undefined) {
    if (!warned.has(key)) { warned.add(key); console.warn(`[i18n] missing key: ${key}`); }
    return key;
  }
  if (typeof entry === "object") entry = entry[rules.select(Number(vars?.n ?? 0))] ?? entry.other;
  if (!vars) return entry;
  return entry.replace(/\{(\w+)\}/g, (m, name) => (vars[name] ?? m));
}

// Translated text if the key exists, otherwise `fallback`. Used for labels that the
// server also sends (session types, bot profiles): the dictionary wins, the server
// text covers anything unknown (e.g. a type added by a plugin).
export function tOr(key, fallback, vars) {
  return lookup(key) !== undefined ? t(key, vars) : fallback;
}

// The server's default driver names are English ("Driver 3"): show them in the UI
// language. A name the user typed is left as it is.
export function driverName(name, slot) {
  return name === `Driver ${slot + 1}` ? t("driver.n", { n: slot + 1 }) : name;
}

// A server log entry in the UI language: "srv.<key>" with its params; the server's English
// text when the entry has no key (older server) or the dictionary does not know it.
export function logText(entry) {
  if (!entry.key || lookup(`srv.${entry.key}`) === undefined) return entry.text;
  const vars = { ...entry.params };
  if (vars.name != null && vars.slot != null) vars.name = driverName(vars.name, vars.slot);
  if (vars.transport) vars.transport = tOr(`srv.transport.${vars.transport}`, vars.transport);
  return t(`srv.${entry.key}`, vars);
}

// Fills the static markup of index.html: data-i18n="key" sets the text, and
// data-i18n-title / -aria-label / -placeholder="key" set the matching attribute.
export function translateStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const attr of ["title", "aria-label", "placeholder"]) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) {
      el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
    }
  }
}
